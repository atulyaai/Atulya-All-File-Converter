def _read_table(filepath, fmt):
    delimiter = "\t" if fmt == "tsv" else ","
    with open(filepath, "r", encoding="utf-8", newline="") as f:
        reader = csv.reader(f, delimiter=delimiter)
        rows = list(reader)
    return {
        "format": fmt,
        "type": "table",
        "headers": rows[0] if rows else [],
        "rows": rows[1:] if len(rows) > 1 else [],
        "row_count": max(0, len(rows) - 1),
        "column_count": len(rows[0]) if rows else 0,
    }


def _read_spreadsheet(filepath):
    import openpyxl
    wb = openpyxl.load_workbook(filepath, read_only=True, data_only=True)
    sheets = {}
    for sheet_name in wb.sheetnames:
        ws = wb[sheet_name]
        rows = []
        for row in ws.iter_rows(values_only=True):
            rows.append(list(row))
        sheets[sheet_name] = {"headers": rows[0] if rows else [], "rows": rows[1:] if len(rows) > 1 else []}
    wb.close()
    return {"format": "xlsx", "type": "workbook", "sheets": sheets, "sheet_names": wb.sheetnames}


def _read_xml(filepath):
    tree = ET.parse(filepath)
    root = tree.getroot()
    return {"format": "xml", "type": "data", "root_tag": root.tag, "data": _xml_to_dict(root)}


def _xml_to_dict(element):
    result = {}
    for child in element:
        if len(child) == 0:
            result[child.tag] = child.text
        else:
            if child.tag not in result:
                result[child.tag] = []
            result[child.tag].append(_xml_to_dict(child))
    return result


