def _convert_by_format(input_path, output_path, fmt_in, fmt_out, kwargs):
    ext_out = os.path.splitext(output_path.lower())[1]

    if fmt_in in ("csv", "tsv", "xlsx", "ods") and fmt_out in ("csv", "tsv", "xlsx", "json", "html", "xml"):
        _convert_tabular(input_path, output_path)
    elif fmt_in in ("json",) and fmt_out in ("csv", "xlsx", "xml", "yaml", "toml", "html"):
        _convert_json_to(input_path, output_path, fmt_out)
    elif fmt_in in ("yaml", "yml") and fmt_out in ("json", "csv", "xlsx", "xml"):
        _convert_yaml_to(input_path, output_path, fmt_out)
    elif fmt_in in ("xml",) and fmt_out in ("json", "csv", "xlsx", "yaml"):
        _convert_xml_to(input_path, output_path, fmt_out)
    elif fmt_in in ("html", "txt", "md", "log", "cfg", "env") and ext_out in {".txt", ".html", ".md"}:
        _convert_text_to(input_path, output_path, fmt_out)
    elif fmt_in in IMAGE_EXTENSIONS or ext_out in IMAGE_EXTENSIONS:
        _convert_image(input_path, output_path, kwargs.get("quality", 90))
    elif fmt_in == "pdf" and fmt_out in ("txt", "html", "json"):
        _convert_pdf(input_path, output_path, fmt_out)
    elif fmt_in in ("zip", "tar", "gz", "bz2", "xz") and fmt_out == "dir":
        extract_archive(input_path, output_path)
    else:
        data = read_file(input_path)
        write_file(data, output_path)


def _convert_tabular(input_path, output_path):
    import pandas as pd
    ext = os.path.splitext(input_path.lower())[1]
    if ext == ".csv":
        df = pd.read_csv(input_path)
    elif ext in (".tsv", ".tab"):
        df = pd.read_csv(input_path, sep="\t")
    else:
        df = pd.read_excel(input_path)
    out_ext = os.path.splitext(output_path.lower())[1]
    if out_ext == ".csv":
        df.to_csv(output_path, index=False)
    elif out_ext in (".xlsx", ".xls"):
        df.to_excel(output_path, index=False, engine="xlsxwriter")
    elif out_ext == ".json":
        df.to_json(output_path, orient="records", indent=2)
    elif out_ext == ".html":
        df.to_html(output_path, index=False)
    elif out_ext == ".xml":
        df.to_xml(output_path, index=False)


def _convert_json_to(input_path, output_path, target_fmt):
    import pandas as pd
    with open(input_path, encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, list):
        df = pd.DataFrame(data)
    else:
        df = pd.DataFrame([data])
    if target_fmt == "csv":
        df.to_csv(output_path, index=False)
    elif target_fmt == "xlsx":
        df.to_excel(output_path, index=False, engine="xlsxwriter")
    elif target_fmt == "xml":
        df.to_xml(output_path, index=False)
    elif target_fmt == "yaml":
        import yaml
        with open(input_path) as f:
            d = json.load(f)
        with open(output_path, "w") as f:
            yaml.dump(d, f, default_flow_style=False)
    elif target_fmt == "toml":
        import tomli_w
        with open(input_path) as f:
            d = json.load(f)
        with open(output_path, "wb") as f:
            tomli_w.dump(d, f)


def _convert_yaml_to(input_path, output_path, target_fmt):
    import yaml
