def _read_docx(filepath):
    try:
        from docx import Document
        doc = Document(filepath)
        paragraphs = [p.text for p in doc.paragraphs]
        return {"format": "docx", "type": "document", "paragraphs": paragraphs, "count": len(paragraphs)}
    except ImportError:
        return {"format": "docx", "type": "document", "error": "Install python-docx: pip install atulya-convert[docx]"}


