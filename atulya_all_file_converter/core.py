def _convert_image(input_path, output_path, quality):
    from PIL import Image
    img = Image.open(input_path)
    out_ext = os.path.splitext(output_path.lower())[1]
    if img.mode == "RGBA" and out_ext in (".jpg", ".jpeg"):
        img = img.convert("RGB")
    save_kwargs = {}
    if out_ext in (".jpg", ".jpeg"):
        save_kwargs["quality"] = quality
    elif out_ext == ".png":
        save_kwargs["compress_level"] = max(0, 9 - quality // 11)
    if out_ext == ".pdf":
        if img.mode != "RGB":
            img = img.convert("RGB")
        img.save(output_path, "PDF", resolution=100)
    else:
        img.save(output_path, **save_kwargs)


def _convert_pdf(input_path, output_path, target_fmt):
    text = _read_pdf_text(input_path)
    if target_fmt == "txt":
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(text)
    elif target_fmt == "html":
        html_content = f"<!DOCTYPE html><html><body><pre>{text}</pre></body></html>"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(html_content)
    elif target_fmt == "json":
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump({"text": text}, f, indent=2)


def _read_pdf_text(filepath):
    try:
        import fitz
        doc = fitz.open(filepath)
        text = "\n".join(page.get_text() for page in doc)
        doc.close()
        return text
    except ImportError:
        try:
            import pdfplumber
            with pdfplumber.open(filepath) as pdf:
                return "\n".join(page.extract_text() or "" for page in pdf.pages)
        except ImportError:
            try:
                import pdfminer
            except ImportError:
                pass
    raise ImportError("PDF support requires PyMuPDF: pip install atulya-convert[pdf]")


