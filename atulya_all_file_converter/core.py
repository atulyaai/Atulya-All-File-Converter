def read_file(filepath, encoding="utf-8"):
    fmt = detect_format(filepath)
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"File not found: {filepath}")

    if fmt in IMAGE_EXTENSIONS or detect_format_by_ext(filepath) in ("jpg", "png", "webp", "bmp", "gif", "tiff", "ico"):
        return _read_image(filepath)
    elif detect_format_by_ext(filepath) in ("json",):
        return _read_json(filepath)
    elif detect_format_by_ext(filepath) in ("csv", "tsv"):
        return _read_table(filepath, fmt)
    elif detect_format_by_ext(filepath) in ("xlsx", "ods"):
        return _read_spreadsheet(filepath)
    elif detect_format_by_ext(filepath) in ("xml",):
        return _read_xml(filepath)
    elif detect_format_by_ext(filepath) in ("yaml", "yml"):
        return _read_yaml(filepath)
    elif detect_format_by_ext(filepath) in ("toml",):
        return _read_toml(filepath)
    elif detect_format_by_ext(filepath) in ("ini", "cfg", "conf"):
        return _read_ini(filepath)
    elif detect_format_by_ext(filepath) in ("zip", "tar", "gz", "bz2", "xz"):
        return _read_archive(filepath)
    elif detect_format_by_ext(filepath) in ("sqlite", "sqlite3", "db"):
        return _read_sqlite(filepath)
    elif detect_format_by_ext(filepath) in ("pdf",):
        return _read_pdf(filepath)
    elif detect_format_by_ext(filepath) in ("docx",):
        return _read_docx(filepath)
    elif detect_format_by_ext(filepath) in ("py", "js", "css"):
        with open(filepath, "r", encoding=encoding, errors="replace") as f:
            return {"format": fmt, "type": "code", "content": f.read(), "lines": f.name and None}
    else:
        with open(filepath, "r", encoding=encoding, errors="replace") as f:
            content = f.read()
        return {
            "format": fmt or "txt",
            "type": "text",
            "content": content,
            "lines": content.splitlines(),
            "encoding": encoding,
        }


def write_file(data, output_path, encoding="utf-8"):
    ensure_output_dir(output_path)
    fmt = detect_format_by_ext(output_path)
    ext = os.path.splitext(output_path.lower())[1]

    if fmt in ("json",):
        _write_json(data, output_path)
    elif fmt in ("csv", "tsv"):
        _write_table(data, output_path, fmt)
    elif fmt in ("xml",):
        _write_xml(data, output_path)
    elif fmt in ("yaml", "yml"):
        _write_yaml(data, output_path)
    elif fmt in ("toml",):
        _write_toml(data, output_path)
    elif fmt in ("ini", "cfg", "conf"):
        _write_ini(data, output_path)
    elif ext in IMAGE_EXTENSIONS:
        _write_image(data, output_path)
    elif fmt in ("zip",):
        _write_zip(data, output_path)
    else:
        if isinstance(data, str):
            content = data
        elif isinstance(data, dict) and "content" in data:
            content = data["content"]
        elif isinstance(data, dict) and "text" in data:
            content = data["text"]
        elif isinstance(data, list):
            content = json.dumps(data, indent=2)
        else:
            content = str(data)
        with open(output_path, "w", encoding=encoding) as f:
            f.write(content)


