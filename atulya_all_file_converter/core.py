def get_file_info(filepath):
    stat = os.stat(filepath)
    fmt = detect_format(filepath)
    cat = get_category(filepath)
    info = {
        "path": os.path.abspath(filepath),
        "name": os.path.basename(filepath),
        "size": stat.st_size,
        "size_human": format_size(stat.st_size),
        "format": fmt or "unknown",
        "category": cat,
        "modified": datetime.datetime.fromtimestamp(stat.st_mtime).isoformat(),
        "created": datetime.datetime.fromtimestamp(stat.st_ctime).isoformat(),
    }

    ext = os.path.splitext(filepath.lower())[1]
    if ext in IMAGE_EXTENSIONS:
        try:
            from PIL import Image
            img = Image.open(filepath)
            info["width"] = img.width
            info["height"] = img.height
            info["mode"] = img.mode
            info["dpi"] = img.info.get("dpi")
            try:
                info["format_detail"] = img.format_description
            except Exception:
                pass
        except ImportError:
            pass

    if cat == "text" or ext in TEXT_EXTENSIONS:
        try:
            with open(filepath, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
            lines = content.splitlines()
            info["lines"] = len(lines)
            info["chars"] = len(content)
            info["words"] = len(content.split())
            info["encoding"] = detect_encoding(filepath)
        except Exception:
            pass

    if ext == ".json":
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, list):
                info["array_length"] = len(data)
            elif isinstance(data, dict):
                info["keys"] = list(data.keys())
        except Exception:
            pass

    if ext == ".pdf":
        try:
            import fitz
            doc = fitz.open(filepath)
            info["pages"] = len(doc)
            doc.close()
        except ImportError:
            try:
                info["pages"] = "unknown (install PyMuPDF)"
            except Exception:
                pass
        except Exception:
            pass

    return info


def compute_file_hash(filepath, algorithms=None):
    if algorithms is None:
        algorithms = ["md5", "sha1", "sha256"]
    result = {}
    for algo in algorithms:
        try:
            result[algo] = compute_hash(filepath, algo)
        except Exception as e:
            result[algo] = str(e)
    return result


def split_file(filepath, chunk_size_mb=10, output_dir=None):
    if output_dir is None:
        output_dir = os.path.dirname(filepath) or "."
    ensure_output_dir(output_dir)

    base = os.path.splitext(os.path.basename(filepath))[0]
    chunk_size = chunk_size_mb * 1024 * 1024
    parts = []

    with open(filepath, "rb") as f:
        part_num = 1
        while True:
            chunk = f.read(chunk_size)
            if not chunk:
                break
            part_path = os.path.join(output_dir, f"{base}.part{part_num:03d}")
            with open(part_path, "wb") as pf:
                pf.write(chunk)
            parts.append(part_path)
            part_num += 1

    return parts


def merge_files(input_paths, output_path):
    ensure_output_dir(output_path)
    with open(output_path, "wb") as out:
        for path in input_paths:
            with open(path, "rb") as f:
                shutil.copyfileobj(f, out)
    return format_size(os.path.getsize(output_path))


def compress_archive(input_paths, output_path, archive_format="zip"):
    ensure_output_dir(output_path)

    if archive_format == "zip":
        with zipfile.ZipFile(output_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for path in input_paths:
                zf.write(path, os.path.basename(path))
    elif archive_format == "tar":
        with tarfile.open(output_path, "w") as tf:
            for path in input_paths:
                tf.add(path, arcname=os.path.basename(path))
    elif archive_format == "targz":
        with tarfile.open(output_path, "w:gz") as tf:
            for path in input_paths:
                tf.add(path, arcname=os.path.basename(path))
    elif archive_format == "tarbz2":
        with tarfile.open(output_path, "w:bz2") as tf:
            for path in input_paths:
                tf.add(path, arcname=os.path.basename(path))
    elif archive_format == "tarxz":
        with tarfile.open(output_path, "w:xz") as tf:
            for path in input_paths:
                tf.add(path, arcname=os.path.basename(path))
    elif archive_format == "gz":
        if len(input_paths) == 1:
            with open(input_paths[0], "rb") as f_in:
                with gzip.open(output_path, "wb") as f_out:
                    shutil.copyfileobj(f_in, f_out)
        else:
            compress_archive(input_paths, output_path + ".tar", "tar")
            with open(output_path + ".tar", "rb") as f_in:
                with gzip.open(output_path, "wb") as f_out:
                    shutil.copyfileobj(f_in, f_out)
            os.remove(output_path + ".tar")
    else:
        raise ValueError(f"Unsupported archive format: {archive_format}")

    return format_size(os.path.getsize(output_path))


def extract_archive(input_path, output_dir):
    ensure_output_dir(output_dir)
    fmt = detect_format(input_path)

    if fmt == "zip":
        with zipfile.ZipFile(input_path, "r") as zf:
            zf.extractall(output_dir)
    elif fmt == "tar":
        with tarfile.open(input_path, "r") as tf:
            tf.extractall(output_dir)
    elif fmt == "gz":
        output_path = os.path.join(output_dir, os.path.splitext(os.path.basename(input_path))[0])
        with gzip.open(input_path, "rb") as f_in:
            with open(output_path, "wb") as f_out:
                shutil.copyfileobj(f_in, f_out)
    elif fmt == "bz2":
        output_path = os.path.join(output_dir, os.path.splitext(os.path.basename(input_path))[0])
        with bz2.open(input_path, "rb") as f_in:
            with open(output_path, "wb") as f_out:
                shutil.copyfileobj(f_in, f_out)
    elif fmt == "xz":
        output_path = os.path.join(output_dir, os.path.splitext(os.path.basename(input_path))[0])
        with lzma.open(input_path, "rb") as f_in:
            with open(output_path, "wb") as f_out:
                shutil.copyfileobj(f_in, f_out)
    else:
        raise ValueError(f"Unsupported archive format: {fmt}")

    extracted = os.listdir(output_dir)
    return extracted


def validate_file(filepath):
    fmt = detect_format(filepath)
    issues = []

    if not os.path.exists(filepath):
        return {"valid": False, "format": fmt, "issues": ["File not found"]}

    if fmt in ("json",):
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                json.load(f)
        except json.JSONDecodeError as e:
            issues.append(f"Invalid JSON: {e}")
    elif fmt in ("xml",):
        try:
            ET.parse(filepath)
        except ET.ParseError as e:
            issues.append(f"Invalid XML: {e}")
    elif fmt in ("yaml", "yml"):
        try:
            import yaml
            with open(filepath, "r", encoding="utf-8") as f:
                yaml.safe_load(f)
        except Exception as e:
            issues.append(f"Invalid YAML: {e}")
    elif fmt in ("toml",):
        try:
            import tomllib
            with open(filepath, "rb") as f:
                tomllib.load(f)
        except ImportError:
            import tomli
            with open(filepath, "rb") as f:
                tomli.load(f)
        except Exception as e:
            issues.append(f"Invalid TOML: {e}")
    elif fmt in ("csv", "tsv"):
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                reader = csv.reader(f)
                for i, row in enumerate(reader):
                    if i > 1000:
                        break
        except Exception as e:
            issues.append(f"CSV read error: {e}")
    elif fmt in ("zip",):
        try:
            with zipfile.ZipFile(filepath, "r") as zf:
                if zf.testzip():
                    issues.append(f"Corrupted zip: {zf.testzip()}")
        except Exception as e:
            issues.append(f"Invalid ZIP: {e}")
    elif fmt in IMAGE_EXTENSIONS or detect_format_by_ext(filepath) in IMAGE_EXTENSIONS:
        try:
            from PIL import Image
            img = Image.open(filepath)
            img.verify()
        except Exception as e:
            issues.append(f"Invalid image: {e}")
    elif fmt in ("pdf",):
        try:
            import fitz
            doc = fitz.open(filepath)
            doc.close()
        except ImportError:
            pass
        except Exception as e:
            issues.append(f"Invalid PDF: {e}")
    elif fmt in ("sqlite",):
        try:
            import sqlite3
            conn = sqlite3.connect(filepath)
            conn.cursor().execute("SELECT 1")
            conn.close()
        except Exception as e:
            issues.append(f"Invalid SQLite: {e}")
    elif fmt in ("docx",):
        try:
            import zipfile
            with zipfile.ZipFile(filepath, "r") as zf:
                if "word/document.xml" not in zf.namelist():
                    issues.append("Not a valid DOCX (missing word/document.xml)")
        except Exception as e:
            issues.append(f"Invalid DOCX: {e}")

    return {"valid": len(issues) == 0, "format": fmt, "issues": issues}


def search_file(filepath, pattern, encoding="utf-8"):
    results = []
    compiled = re.compile(pattern, re.IGNORECASE) if isinstance(pattern, str) else pattern

    if is_text_file(filepath):
        with open(filepath, "r", encoding=encoding, errors="replace") as f:
            for i, line in enumerate(f, 1):
                matches = list(compiled.finditer(line.rstrip()))
                if matches:
                    results.append({
                        "line": i,
                        "text": line.rstrip()[:200],
                        "matches": [m.group() for m in matches],
                        "positions": [m.start() for m in matches],
                    })
    else:
        try:
            from PIL import Image
            img = Image.open(filepath)
            import pytesseract
            text = pytesseract.image_to_string(img)
            for i, line in enumerate(text.splitlines(), 1):
                if compiled.search(line):
                    results.append({"line": i, "text": line[:200], "matches": [m.group() for m in compiled.finditer(line)]})
        except ImportError:
            pass

    return results


def count_stats(filepath):
    stats = {"size": format_size(os.path.getsize(filepath))}

    if is_text_file(filepath):
        with open(filepath, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        lines = content.splitlines()
        stats["lines"] = len(lines)
        stats["chars"] = len(content)
        stats["chars_no_spaces"] = len(content.replace(" ", "").replace("\n", "").replace("\r", "").replace("\t", ""))
        stats["words"] = len(content.split())
        non_empty = [l for l in lines if l.strip()]
        stats["code_lines"] = len(non_empty)
        stats["empty_lines"] = len(lines) - len(non_empty)
        stats["max_line_length"] = max((len(l) for l in lines), default=0)
        stats["avg_line_length"] = round(sum(len(l) for l in lines) / max(len(lines), 1), 1)

    if os.path.splitext(filepath.lower())[1] in IMAGE_EXTENSIONS:
        try:
            from PIL import Image
            img = Image.open(filepath)
            stats["width"] = img.width
            stats["height"] = img.height
            stats["megapixels"] = round(img.width * img.height / 1_000_000, 2)
        except ImportError:
            pass

    return stats


def show_schema(filepath):
    fmt = detect_format(filepath)
    schema = {"format": fmt, "type": get_category(filepath)}

    if fmt in ("json",):
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        schema["root_type"] = type(data).__name__
        if isinstance(data, dict):
            schema["keys"] = list(data.keys())
            schema["key_count"] = len(data)
            _infer_types(data, schema)
        elif isinstance(data, list):
            schema["length"] = len(data)
            if data:
                schema["item_type"] = type(data[0]).__name__
                if isinstance(data[0], dict):
                    schema["item_keys"] = list(data[0].keys())
    elif fmt in ("csv", "tsv"):
        with open(filepath, "r", encoding="utf-8") as f:
            reader = csv.reader(f)
            headers = next(reader, [])
            schema["columns"] = headers
            schema["column_count"] = len(headers)
            rows = list(reader)
            schema["row_count"] = len(rows)
    elif fmt in ("xlsx",):
        try:
            import openpyxl
            wb = openpyxl.load_workbook(filepath, read_only=True)
            schema["sheets"] = wb.sheetnames
            schema["sheet_count"] = len(wb.sheetnames)
            ws = wb.active
            if ws:
                schema["active_sheet"] = ws.title
                schema["dimensions"] = ws.dimensions
            wb.close()
        except ImportError:
            schema["sheets"] = "unknown (install openpyxl)"
    elif fmt in ("xml",):
        tree = ET.parse(filepath)
        root = tree.getroot()
        schema["root_tag"] = root.tag
        schema["root_attribs"] = list(root.attrib.keys()) if root.attrib else None
        schema["children"] = list({child.tag for child in root})

    return schema


def generate_random(output_path, lines=10):
    ensure_output_dir(output_path)
    fmt = detect_format_by_ext(output_path) or os.path.splitext(output_path.lower())[1].lstrip(".")
    import random
    import string

    if fmt in ("json",):
        data = {f"field_{i}": f"value_{random.randint(1, 100)}" for i in range(lines)}
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
    elif fmt in ("csv", "tsv"):
        delimiter = "\t" if fmt == "tsv" else ","
        with open(output_path, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f, delimiter=delimiter)
            writer.writerow(["id", "name", "value", "active"])
            for i in range(lines):
                writer.writerow([i, f"item_{i}", random.randint(1, 1000), random.choice([True, False])])
    elif fmt in ("xml",):
        root = ET.Element("records")
        for i in range(lines):
            item = ET.SubElement(root, "record", id=str(i))
            ET.SubElement(item, "name").text = f"item_{i}"
            ET.SubElement(item, "value").text = str(random.randint(1, 1000))
        tree = ET.ElementTree(root)
        tree.write(output_path, encoding="utf-8", xml_declaration=True)
    else:
        with open(output_path, "w", encoding="utf-8") as f:
            for i in range(lines):
                f.write(f"Line {i+1}: {''.join(random.choices(string.ascii_letters + string.digits, k=40))}\n")

    return format_size(os.path.getsize(output_path))


def diff_files(filepath_a, filepath_b):
    if is_text_file(filepath_a) and is_text_file(filepath_b):
        with open(filepath_a, "r", encoding="utf-8", errors="replace") as f:
            lines_a = f.readlines()
        with open(filepath_b, "r", encoding="utf-8", errors="replace") as f:
            lines_b = f.readlines()

        diff = list(difflib.context_diff(lines_a, lines_b, fromfile=filepath_a, tofile=filepath_b, n=3))
        return {"type": "text", "diff": diff, "diffs": len(diff) > 0}
    else:
        stat_a = os.stat(filepath_a)
        stat_b = os.stat(filepath_b)
        return {
            "type": "binary",
            "size_a": stat_a.st_size,
            "size_b": stat_b.st_size,
            "same_size": stat_a.st_size == stat_b.st_size,
            "hash_a": compute_hash(filepath_a, "sha256"),
            "hash_b": compute_hash(filepath_b, "sha256"),
            "identical": compute_hash(filepath_a, "sha256") == compute_hash(filepath_b, "sha256"),
        }


def batch_convert(input_dir, pattern, output_dir, output_format, **kwargs):
    import glob
    matched = glob.glob(os.path.join(input_dir, pattern))
    results = []
    for input_path in sorted(matched):
        base = os.path.splitext(os.path.basename(input_path))[0]
        output_path = os.path.join(output_dir, f"{base}.{output_format}")
        try:
            result = convert_file(input_path, output_path, **kwargs)
            results.append((base, "ok", result))
        except Exception as e:
            results.append((base, "error", str(e)))
    return results


