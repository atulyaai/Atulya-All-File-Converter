def _write_table(data, output_path, fmt):
    delimiter = "\t" if fmt == "tsv" else ","
    if isinstance(data, dict):
        headers = data.get("headers", [])
        rows = data.get("rows", [])
    elif isinstance(data, list) and data and isinstance(data[0], dict):
        headers = list(data[0].keys())
        rows = [[row.get(h, "") for h in headers] for row in data]
    elif isinstance(data, list) and data and isinstance(data[0], list):
        headers = data[0] if data else []
        rows = data[1:] if len(data) > 1 else []
    else:
        headers = ["value"]
        rows = [[d] for d in data] if isinstance(data, list) else [[str(data)]]
    with open(output_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, delimiter=delimiter)
        if headers:
            writer.writerow(headers)
        writer.writerows(rows)


def _write_xml(data, output_path):
    if isinstance(data, dict) and "data" in data:
        data = data["data"]
    if isinstance(data, dict):
        root = ET.Element("root")
        for key, val in data.items():
            child = ET.SubElement(root, key)
            child.text = str(val)
        tree = ET.ElementTree(root)
    elif isinstance(data, list):
        root = ET.Element("records")
        for i, item in enumerate(data):
            if isinstance(item, dict):
                record = ET.SubElement(root, "record", id=str(i))
                for k, v in item.items():
                    ET.SubElement(record, k).text = str(v)
        tree = ET.ElementTree(root)
    else:
        root = ET.Element("data")
        root.text = str(data)
        tree = ET.ElementTree(root)
    tree.write(output_path, encoding="utf-8", xml_declaration=True)


